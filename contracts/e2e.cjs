// END-TO-END on a local EVM with the REAL Coinbase Smart Wallet + EntryPoint v0.6 + SwissRecoveryModule.
// Every calldata / userOpHash / passkey (WebAuthn P-256) signature is produced by the app's Kotlin code
// (kotlin-harness/harness.jar, built by kotlin-harness/build.sh). Node only plays the role of the bundler (calls EntryPoint.handleOps).
const assert = require('assert');
const { execFileSync } = require('child_process');
const ganache = require('ganache');
const { BrowserProvider, ContractFactory, Contract, Wallet, AbiCoder, getBytes, parseEther, zeroPadValue } = require('ethers');
const fs = require('fs');

const kt = (...args) => execFileSync('java', ['-jar', require('path').join(__dirname, 'kotlin-harness', 'harness.jar'), ...args.map(String)], { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
const load = (n) => JSON.parse(fs.readFileSync(`build/e2e/${n}.json`));
const coder = AbiCoder.defaultAbiCoder();
const CHAIN_ID = 1337;

(async () => {
  const provider = new BrowserProvider(ganache.provider({ logging: { quiet: true }, chain: { chainId: CHAIN_ID, hardfork: 'shanghai' }, miner: { blockGasLimit: 60_000_000 }, wallet: { defaultBalance: 1000 } }));
  const bundler = await provider.getSigner(0);
  const deploy = async (name, ...args) => { const j = load(name); const c = await new ContractFactory(j.abi, j.bytecode, bundler).deploy(...args, { gasLimit: 30_000_000 }); await c.waitForDeployment(); return c; };

  // Coinbase Smart Wallet hardcodes the canonical EntryPoint v0.6 address → put the EntryPoint code there.
  const epTmp = await deploy('EntryPoint');
  const CANON_EP = '0x5FF137D4b0FDCD49DcA30c7CF57E578a026d2789';
  await provider.send('evm_setAccountCode', [CANON_EP, await provider.getCode(await epTmp.getAddress())]);
  const ep = new Contract(CANON_EP, load('EntryPoint').abi, bundler);
  const impl = await deploy('CoinbaseSmartWallet');
  const factory = await deploy('CoinbaseSmartWalletFactory', await impl.getAddress());
  // Arachnid's deterministic CREATE2 proxy (present on Base Sepolia / most chains) at its canonical address.
  const CREATE2 = '0x4e59b44847b379578588920cA78FbF26c0B4956C';
  await provider.send('evm_setAccountCode', [CREATE2, '0x7fffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffe03601600081602082378035828234f58015156039578182fd5b8082525050506014600cf3']);
  // The module is NOT deployed yet: the wallet will deploy it itself (like the app does on a fresh chain).
  const MODULE = kt('module');
  const mod = new Contract(MODULE, load('SwissRecoveryModule').abi, provider);
  const [EP, FACTORY] = await Promise.all([ep.getAddress(), factory.getAddress()]);
  assert.strictEqual(await provider.getCode(MODULE), '0x');
  console.log('deployed EntryPoint v0.6 + Coinbase factory; module address (not deployed yet):', MODULE);

  // ---- 1. Passkey #1 (phone) — generated by the Kotlin code (P-256)
  const [pk1, x1, y1] = kt('keygen').split(' ');
  const owners = [coder.encode(['bytes32', 'bytes32'], [x1, y1]), zeroPadValue(MODULE, 32)];
  const wallet = await factory["getAddress(bytes[],uint256)"](owners, 0);
  const initCode = kt('initcode', FACTORY, x1, y1, MODULE);
  await (await bundler.sendTransaction({ to: wallet, value: parseEther('1') })).wait();
  console.log('counterfactual wallet', wallet, 'funded with 1 ETH before it even exists');

  const W = new Contract(wallet, load('CoinbaseSmartWallet').abi, provider);
  const sendOp = async (pk, ownerIndex, callData, withInit = false, sender = wallet, senderInit = initCode) => {
    const nonce = await ep.getNonce(sender, 0);
    const op = { sender, nonce, initCode: withInit ? senderInit : '0x', callData, callGasLimit: 3_000_000n, verificationGasLimit: 3_000_000n, preVerificationGas: 100_000n, maxFeePerGas: 2_000_000_000n, maxPriorityFeePerGas: 1_000_000_000n, paymasterAndData: '0x' };
    const [hash, signature] = kt('sign', pk, ownerIndex, EP, CHAIN_ID, op.sender, op.nonce, op.initCode, op.callData, op.callGasLimit, op.verificationGasLimit, op.preVerificationGas, op.maxFeePerGas, op.maxPriorityFeePerGas, op.paymasterAndData).split(' ');
    assert.strictEqual(hash, await ep.getUserOpHash({ ...op, signature: '0x' }), 'Kotlin userOpHash must equal EntryPoint.getUserOpHash');
    try { await ep.connect(bundler).handleOps.staticCall([{ ...op, signature }], await bundler.getAddress(), { gasLimit: 10_000_000 }); }
    catch (e) { const d = e.data || e.info?.error?.data?.data || e.info?.error?.data; let parsed = null; try { parsed = ep.interface.parseError(typeof d === 'string' ? d : d?.data); } catch {} ; throw new Error('handleOps would revert: ' + (parsed ? parsed.name + ' ' + parsed.args.join(' | ') : JSON.stringify(d))); }
    const tx = await ep.connect(bundler).handleOps([{ ...op, signature }], await bundler.getAddress(), { gasLimit: 10_000_000 });
    const rc = await tx.wait();
    const ev = rc.logs.map((l) => { try { return ep.interface.parseLog(l); } catch { return null; } }).find((e) => e?.name === 'UserOperationEvent');
    return ev.args.success;
  };

  // ---- 2. First op: deploys the wallet + sends 0.1 ETH, signed by the passkey (WebAuthn, verified on-chain)
  const bob = Wallet.createRandom().address;
  assert.strictEqual(await sendOp(pk1, 0, kt('execute', bob, parseEther('0.1'), '0x'), true), true);
  assert.strictEqual(await provider.getBalance(bob), parseEther('0.1'));
  console.log('✔ op#1 deploy + transfer signed by passkey #1 (WebAuthn P-256 verified on-chain)');

  // ---- 3. "Activate protection": executeBatch([CREATE2 deploy module, setupGuardians(4, 3, 30 s)]) — exactly the app's call
  const guardians = [0, 1, 2, 3].map(() => Wallet.createRandom()); // Swissquote, my device, close one, close one
  assert.strictEqual(await sendOp(pk1, 0, kt('activate', guardians.map((g) => g.address).join(','), 3, 30)), true);
  assert.notStrictEqual(await provider.getCode(MODULE), '0x', 'module must now be deployed at the CREATE2 address computed by Kotlin');
  const cfg = await mod.configOf(wallet);
  assert.deepStrictEqual([cfg[0], cfg[1], cfg[3]], [3n, 30n, 4n]);
  console.log('✔ op#2 executeBatch: module deployed via CREATE2 + setupGuardians(3-of-4, 30 s)');

  // ---- 3b. Attack: 3 guardians collude (or are tricked) to add a thief's key. The owner still has the phone → cancels.
  {
    const [, xt, yt] = kt('keygen').split(' ');
    const n0 = (await mod.configOf(wallet))[2];
    const rht = kt('recoveryhash', wallet, xt, yt, 0, n0, CHAIN_ID, MODULE);
    const st = await Promise.all([0, 1, 2].map((i) => guardians[i].signMessage(getBytes(rht))));
    await (await bundler.sendTransaction({ to: MODULE, data: kt('initiate', wallet, xt, yt, 0, st.join(',')), gasLimit: 1_000_000 })).wait();
    assert.strictEqual((await mod.pendingOf(wallet))[4], true);
    assert.strictEqual(await sendOp(pk1, 0, kt('execute', MODULE, 0, '0x0ba234d6' /* cancelRecovery() */)), true);
    assert.strictEqual((await mod.pendingOf(wallet))[4], false);
    console.log('✔ attack: a recovery started without the owner → owner cancels it during the delay (passkey #1)');
  }

  // ---- 4. Phone lost. New passkey #2 on a new device.
  const [pk2, x2, y2] = kt('keygen').split(' ');
  const nonce = (await mod.configOf(wallet))[2];
  const rh = kt('recoveryhash', wallet, x2, y2, 0, nonce, CHAIN_ID, MODULE);
  assert.strictEqual(rh, await mod.recoveryHash(wallet, x2, y2, 0), 'Kotlin RecoveryRequest.hash must equal on-chain recoveryHash');
  const sigs = await Promise.all([0, 1, 3].map((i) => guardians[i].signMessage(getBytes(rh))));
  // The new phone sends it from a "helper" Coinbase wallet owned by passkey #2 only (deployed by this same op).
  const helperOwners = [coder.encode(['bytes32', 'bytes32'], [x2, y2])];
  const helper = await factory["getAddress(bytes[],uint256)"](helperOwners, 0);
  const helperInit = kt('helperinit', FACTORY, x2, y2);
  await (await bundler.sendTransaction({ to: helper, value: parseEther('0.1') })).wait(); // (Pimlico pays in the app)
  assert.strictEqual(await sendOp(pk2, 0, kt('execute', MODULE, 0, kt('initiate', wallet, x2, y2, 0, sigs.join(','))), true, helper, helperInit), true);
  assert.strictEqual((await mod.pendingOf(wallet))[4], true);
  console.log('✔ 3 guardians approved → initiateRecovery sent by the new phone (helper account) → timer started');
  // too early → must revert with TooEarly
  let early = false;
  try { await sendOp(pk2, 0, kt('execute', MODULE, 0, kt('finalize', wallet)), false, helper); } catch (e) { early = true; }
  if (!early) { early = !(await W.isOwnerBytes(coder.encode(['bytes32', 'bytes32'], [x2, y2]))); }
  assert.ok(early, 'finalize before the delay must fail');
  console.log('✔ finalize before 30 s is refused (TooEarly)');

  // the lost passkey still works during the delay (the owner could cancel) …
  await provider.send('evm_increaseTime', [31]); await provider.send('evm_mine', []);
  assert.strictEqual(await sendOp(pk2, 0, kt('execute', MODULE, 0, kt('finalize', wallet)), false, helper), true);
  const newOwner = coder.encode(['bytes32', 'bytes32'], [x2, y2]);
  assert.strictEqual(await W.isOwnerBytes(newOwner), true);
  assert.strictEqual(await W.isOwnerBytes(owners[0]), false);
  assert.strictEqual(await W.isOwnerBytes(owners[1]), true);
  const idx = Number((await W.nextOwnerIndex()) - 1n);
  console.log(`✔ after 30 s: passkey #2 added at index ${idx}, lost passkey #1 removed, module kept`);

  // ---- 5. New phone spends; old passkey is rejected
  const carol = Wallet.createRandom().address;
  assert.strictEqual(await sendOp(pk2, idx, kt('execute', carol, parseEther('0.2'), '0x')), true);
  assert.strictEqual(await provider.getBalance(carol), parseEther('0.2'));
  console.log('✔ new passkey #2 controls the SAME wallet (same address, same funds)');
  let rejected = false;
  try { await sendOp(pk1, 0, kt('execute', carol, 1, '0x')); } catch (e) { rejected = /AA2[34]|signature/i.test(String(e.message) + JSON.stringify(e.info ?? {})); }
  assert.ok(rejected, 'old passkey must be rejected');
  console.log('✔ lost passkey #1 is rejected by the EntryPoint (owner index 0 no longer exists)');
  console.log('\nE2E PASSED');
  process.exit(0);
})().catch((e) => { console.error(e); process.exit(1); });
